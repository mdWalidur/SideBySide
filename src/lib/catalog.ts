function buildStructuredSpecs(specs: Record<string, string>): Record<string, SpecValue> {
  const result: Record<string, SpecValue> = {};
  for (const [label, value] of Object.entries(specs)) {
    const matchedRule = specMetadataRules.find((rule) => rule.pattern.test(label));
    const numericValue = matchedRule?.extractor ? matchedRule.extractor(value) : undefined;
    // Special override: lower noise dB is better
    const higherIsBetter = /noise$/i.test(label) ? false : matchedRule?.higherIsBetter;
    result[label] = {
      value,
      numericValue,
      unit: matchedRule?.unit,
      higherIsBetter,
      group: matchedRule?.group ?? "Performance & Hardware",
    };
  }
  return result;
}


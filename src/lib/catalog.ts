function buildPriceHistory(basePrice: number): PricePoint[] {
  const months = ["May", "Jun", "Jul", "Aug", "Sep", "Oct"];
  const multipliers = [1.12, 1.09, 1.05, 1.06, 1.02, 1.0];
  return months.map((month, idx) => {
    const lowEur = Math.max(12, Math.round(basePrice * multipliers[idx]));
    const avgEur = Math.max(14, Math.round(lowEur * 1.04));
    return { month, lowEur, avgEur };
  });
}

